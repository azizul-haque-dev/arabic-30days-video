// Generates src/timing.ts from data/day5.srt — every scene/beat time is derived from the SRT.
// Inside a cue, a marker's time is interpolated by (weighted) character position;
// the untranscribed Arabic phrase ("[বিদেশি ভাষা]") is given a fixed speech-weight.
import fs from "node:fs";

const FPS = 30;
const LEAD = 5; // visuals land ~5 frames before the spoken words
const ARABIC_WEIGHT = 46; // character-equivalents for one "[বিদেশি ভাষা]" block (spoken twice)

const raw = fs.readFileSync(new URL("../data/day5.srt", import.meta.url), "utf8").replace(/\r/g, "");
const ts = (s) => {
  const [h, m, r] = s.split(":");
  const [sec, ms] = r.split(",");
  return +h * 3600 + +m * 60 + +sec + +ms / 1000;
};
const cues = raw
  .trim()
  .split(/\n\n+/)
  .map((b) => {
    const l = b.split("\n");
    const [a, z] = l[1].split(" --> ");
    return { n: +l[0], s: ts(a), e: ts(z), t: l.slice(2).join(" ").replace("[বিদেশি ভাষা]", "§").replace(/\s+/g, " ").trim() };
  });
const cue = (n) => cues.find((c) => c.n === n);
const weight = (str) => [...str].reduce((a, ch) => a + (ch === "§" ? ARABIC_WEIGHT : 1), 0);

// time (sec) of the first (or last) occurrence of `mark` in cue n; "end" = end of the marker
function at(n, mark, opts = {}) {
  const c = cue(n);
  if (mark === undefined) return c.s;
  const idx = opts.last ? c.t.lastIndexOf(mark) : c.t.indexOf(mark, opts.from ?? 0);
  if (idx < 0) throw new Error(`marker "${mark}" not in cue ${n}: ${c.t}`);
  const pos = idx + (opts.end ? mark.length : 0);
  const frac = weight(c.t.slice(0, pos)) / weight(c.t);
  return c.s + frac * (c.e - c.s);
}
const f = (sec) => Math.round(sec * FPS);
const startF = (sec) => Math.max(0, f(sec) - LEAD);

const END_SEC = cues[cues.length - 1].e;
const TOTAL = Math.ceil(END_SEC * FPS);

// ---- scene anchors (start = marker time − LEAD) ----
const starts = {
  hook: 0,
  gulf: startF(at(1, "পর্ব পাঁচে")),
  count: startF(at(2, "দশটি")),
  hub: startF(at(3)),
  twice: startF(at(4, "প্রতিটি")),
  s1: startF(at(5, "Sentence এক")),
  s2: startF(at(8, "Sentence দুই")),
  s3: startF(at(9, "Sentence তিন")),
  s4: startF(at(11, "Sentence চার")),
  s5: startF(at(13, "Sentence পাঁচ")),
  s6: startF(at(15, "Sentence ছয়")),
  s7: startF(at(17, "Sentence সাত")),
  s8: startF(at(19, "Sentence আট")),
  s9: startF(at(20, "Sentence", { last: true })),
  s10: startF(at(23, "Sentence দশ")),
  recap: startF(at(24, "এই ছিল আজকের")),
  comment: startF(at(25, "আপনার")),
  statement: startF(at(26, "আরবি শিখুন")),
  follow: startF(at(26, "প্রতিদিনের lesson")),
  end: startF(at(27, "দেখা হবে")),
};
const order = Object.keys(starts);
const scenes = order.map((id, i) => {
  const from = starts[id];
  const to = i + 1 < order.length ? starts[order[i + 1]] : TOTAL;
  return { id, from, dur: to - from };
});

// ---- in-scene beats (absolute frame; the scene converts to local = abs − from) ----
const sayMarks = [
  // [sentence cue with "বলুন,", cue with "অর্থ,"]
  [6, 7], [9, 9], [10, 11], [12, 12], [13, 14], [16, 16], [18, 18], [20, 20], [21, 22], [23, 24],
];
const sayCues = [
  { say: [6, "বলুন,"], mean: [7, "অর্থ,"] },
  { say: [9, "বলুন,"], mean: [9, "অর্থ,"] },
  { say: [10, "বলুন,"], mean: [11, "অর্থ,"] },
  { say: [11, "বলুন,"], mean: [12, "অর্থ,"] },
  { say: [13, "বলুন,"], mean: [14, "অর্থ,"] },
  { say: [16, "বলুন,"], mean: [16, "অর্থ,"] },
  { say: [17, "বলুন,"], mean: [18, "অর্থ,"] },
  { say: [19, "বলুন,"], mean: [20, "অর্থ,"] },
  { say: [21, "বলুন,"], mean: [22, "অর্থ,"] },
  { say: [23, "বলুন,"], mean: [24, "অর্থ,"] },
];
// cue 11 contains both "Sentence চার" and the "বলুন," of sentence 4 → use the LAST "বলুন," in cue 11
const beats = sayCues.map((b, i) => {
  const lastSay = i === 3; // sentence 4 say lives at end of cue 11
  const say = at(b.say[0], b.say[1], { end: true, last: lastSay || i === 0 && false });
  const mean = at(b.mean[0], b.mean[1]);
  return { say: f(say) - 2, mean: f(mean) - 4 };
});

// ---- other beats ----
const extra = {
  hubSpokes: [f(at(3, "মানুষের")), f(at(3, "পরিবার")), f(at(4, "সম্পর্কে"))].map((x) => x - LEAD),
  twiceListen: f(at(5, "শুনে শুনে")) - LEAD,
  twiceStart: f(at(5, "চলুন শুরু")) - LEAD,
  recapEnd: f(at(25, "আপনার")),
};

const out = `// AUTO-GENERATED by scripts/gen-timing.mjs from data/day5.srt — do not edit by hand.
export const FPS = ${FPS};
export const TOTAL_FRAMES = ${TOTAL};
export const SCENES = ${JSON.stringify(scenes, null, 2)} as const;
export type SceneId = (typeof SCENES)[number]["id"];
export const BEATS = ${JSON.stringify(beats, null, 2)};
export const EXTRA = ${JSON.stringify(extra, null, 2)};
`;
fs.writeFileSync(new URL("../src/timing.ts", import.meta.url), out);
console.log("total", TOTAL, "frames", (TOTAL / FPS).toFixed(2), "s");
for (const s of scenes) console.log(s.id.padEnd(10), (s.from / FPS).toFixed(2).padStart(7), "dur", (s.dur / FPS).toFixed(2));
console.log(beats.map((b, i) => `s${i + 1}: say ${(b.say / FPS).toFixed(2)} mean ${(b.mean / FPS).toFixed(2)}`).join("\n"));
console.log(extra);
