// Generates src/timing.ts from data/day9.srt
import fs from "node:fs";

const FPS = 30;
const LEAD = 5; // Visuals land ~5 frames before spoken words

const raw = fs.readFileSync(new URL("../data/day9.srt", import.meta.url), "utf8").replace(/\r/g, "");
const ts = (s) => {
  const [h, m, r] = s.split(":");
  const [sec, ms] = r.split(",");
  return +h * 3600 + +m * 60 + +sec + +ms / 1000;
};

const cues = raw
  .trim()
  .split(/\n\n+/)
  .map((b) => {
    const l = b.split("\n");
    const [a, z] = l[1].split(" --> ");
    return {
      n: +l[0],
      s: ts(a),
      e: ts(z),
      t: l.slice(2).join(" ").replace(/\s+/g, " ").trim(),
    };
  });

const cue = (n) => cues.find((c) => c.n === n);

function at(n, mark, opts = {}) {
  const c = cue(n);
  if (!mark) return c.s;
  const idx = opts.last ? c.t.lastIndexOf(mark) : c.t.indexOf(mark, opts.from ?? 0);
  if (idx < 0) throw new Error(`Marker "${mark}" not found in cue ${n}: "${c.t}"`);
  const pos = idx + (opts.end ? mark.length : 0);
  const frac = pos / c.t.length;
  return c.s + frac * (c.e - c.s);
}

const f = (sec) => Math.round(sec * FPS);
const startF = (sec) => Math.max(0, f(sec) - LEAD);

const END_SEC = cues[cues.length - 1].e;
const TOTAL_FRAMES = Math.ceil(END_SEC * FPS);

const starts = {
  hook: 0,
  intro: startF(at(1, "আপনার")),
  progress: startF(at(3, "আলহামদুলিল্লাহ")),
  today: startF(at(3, "আজ শিখব")),
  s81: startF(at(5, "Sentence eighty-one")),
  s82: startF(at(6, "Sentence eighty-two")),
  s83: startF(at(7, "Sentence eighty-three")),
  s84: startF(at(8, "Sentence eighty-four")),
  s85: startF(at(10, "Sentence eighty-five")),
  s86: startF(at(11, "Sentence eighty-six")),
  s87: startF(at(13, "Sentence eighty-seven")),
  s88: startF(at(15, "Sentence eighty-eight")),
  s89: startF(at(15, "Sentence", { last: true })),
  s90: startF(at(17, "Sentence ninety")),
  recap: startF(at(18, "Arabic")),
  advice: startF(at(20, "মনে রাখবেন")),
  cta: startF(at(21, "প্রতিদিন নতুন")),
  end: startF(at(22, "দেখা হবে")),
};

const order = Object.keys(starts);
const scenes = order.map((id, i) => {
  const from = starts[id];
  const to = i + 1 < order.length ? starts[order[i + 1]] : TOTAL_FRAMES;
  return { id, from, dur: to - from };
});

// Calculate intra-scene beats for the 10 sentences
// Beat 1: Arabic phrase start (say)
// Beat 2: Bengali meaning start (mean)
const sentenceBeats = [
  // s81: cue 5
  { say: at(5, "جوالي"), mean: at(6, "আমার মোবাইলে") },
  // s82: cue 6/7
  { say: at(6, "عندك"), mean: at(7, "আপনার কাছে") },
  // s83: cue 7/8
  { say: at(7, "كم رمز"), mean: at(8, "Wi-Fi") },
  // s84: cue 9
  { say: at(9, "النت"), mean: at(9, "নেট খুবই") },
  // s85: cue 10/11
  { say: at(10, "دقيت"), mean: at(10, "আপনাকে কল") },
  // s86: cue 11/13
  { say: at(11, "كان الجوال"), mean: at(13, "মোবাইল silent") },
  // s87: cue 13/14
  { say: at(13, "أرسلت"), mean: at(14, "WhatsApp") },
  // s88: cue 15
  { say: at(15, "شوف الصورة"), mean: at(15, "এই ছবিটা") },
  // s89: cue 17
  { say: at(17, "مين يدق"), mean: at(17, "দরজায় কে") },
  // s90: cue 18
  { say: at(18, "شوف مين"), mean: at(18, "দেখুন তো") },
];

const beats = sentenceBeats.map((b) => ({
  say: f(b.say) - 2,
  mean: f(b.mean) - 4,
}));

const out = `// AUTO-GENERATED by scripts/gen-timing.mjs from data/day9.srt — do not edit by hand.
export const FPS = ${FPS};
export const TOTAL_FRAMES = ${TOTAL_FRAMES};
export const SCENES = ${JSON.stringify(scenes, null, 2)} as const;
export type SceneId = (typeof SCENES)[number]["id"];
export const BEATS = ${JSON.stringify(beats, null, 2)};
`;

fs.writeFileSync(new URL("../src/timing.ts", import.meta.url), out);
console.log(`Generated src/timing.ts: ${TOTAL_FRAMES} frames (${(TOTAL_FRAMES / FPS).toFixed(2)}s), ${scenes.length} scenes.`);
for (const s of scenes) {
  console.log(`  ${s.id.padEnd(10)}: from frame ${String(s.from).padStart(4)} to ${String(s.from + s.dur).padStart(4)} (${(s.dur / 30).toFixed(2)}s)`);
}
