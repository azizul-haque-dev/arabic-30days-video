// Generates src/timing.ts from data/day10.srt
import fs from "node:fs";

const FPS = 30;
const LEAD = 5; // Visuals land ~5 frames before spoken words

const raw = fs.readFileSync(new URL("../data/day10.srt", import.meta.url), "utf8").replace(/\r/g, "");
const ts = (s) => {
  const [h, m, r] = s.split(":");
  const [sec, ms] = r.split(",");
  return +h * 3600 + +m * 60 + +sec + +ms / 1000;
};

const cues = raw
  .trim()
  .split(/\n\n+/)
  .map((b) => {
    const l = b.split("\n");
    const [a, z] = l[1].split(" --> ");
    return {
      n: +l[0],
      s: ts(a),
      e: ts(z),
      t: l.slice(2).join(" ").replace(/\s+/g, " ").trim(),
    };
  });

const cue = (n) => cues.find((c) => c.n === n);

function at(n, mark, opts = {}) {
  const c = cue(n);
  if (!mark) return c.s;
  const idx = opts.last ? c.t.lastIndexOf(mark) : c.t.indexOf(mark, opts.from ?? 0);
  if (idx < 0) throw new Error(`Marker "${mark}" not found in cue ${n}: "${c.t}"`);
  const pos = idx + (opts.end ? mark.length : 0);
  const frac = pos / c.t.length;
  return c.s + frac * (c.e - c.s);
}

const f = (sec) => Math.round(sec * FPS);
const startF = (sec) => Math.max(0, f(sec) - LEAD);

const END_SEC = cues[cues.length - 1].e;
const TOTAL_FRAMES = Math.ceil(END_SEC * FPS);

const starts = {
  hook: 0,
  intro: startF(at(2, "আপনার")),
  progress: startF(at(3, "আলহামদুলিল্লাহ")),
  today: startF(at(4, "আজ শিখব")),
  s91: startF(at(6, "Sentence ninety one")),
  s92: startF(at(8, "Sentence ninety two")),
  s93: startF(at(10, "Sentence ninety three")),
  s94: startF(at(12, "Sentence ninety four")),
  s95: startF(at(14, "Sentence ninety five")),
  s96: startF(at(16, "Sentence ninety six")),
  s97: startF(at(19, "Sentence ninety seven")),
  s98: startF(at(21, "Sentence ninety eight")),
  s99: startF(at(22, "Sentence ninety nine")),
  s100: startF(at(24, "Sentence hundred")),
  recap: startF(at(26, "Arabic Master")),
  advice: startF(at(29, "মনে রাখবেন")),
  cta: startF(at(30, "প্রতিদিন নতুন")),
  end: startF(at(31, "দেখা হবে")),
};

const order = Object.keys(starts);
const scenes = order.map((id, i) => {
  const from = starts[id];
  const to = i + 1 < order.length ? starts[order[i + 1]] : TOTAL_FRAMES;
  return { id, from, dur: to - from };
});

// Calculate intra-scene beats for the 10 sentences
// Beat 1: Arabic phrase start (say)
// Beat 2: Bengali meaning start (mean)
const sentenceBeats = [
  // s91: cue 6/7
  { say: at(7, "[আরবি"), mean: at(7, "অর্থ") },
  // s92: cue 8/9
  { say: at(8, "[আরবি"), mean: at(9, "অর্থ") },
  // s93: cue 10/11
  { say: at(11, "[আরবি"), mean: at(11, "অর্থ") },
  // s94: cue 12/13/14
  { say: at(13, "[আরবি"), mean: at(13, "অর্থ") },
  // s95: cue 14/15/16
  { say: at(15, "[আরবি"), mean: at(16, "অর্থ") },
  // s96: cue 16/17/18
  { say: at(17, "[আরবি"), mean: at(18, "অর্থ") },
  // s97: cue 19/20
  { say: at(20, "[আরবি"), mean: at(20, "অর্থ") },
  // s98: cue 21
  { say: at(21, "[আরবি"), mean: at(21, "অর্থ") },
  // s99: cue 22/23
  { say: at(23, "[আরবি"), mean: at(23, "অর্থ") },
  // s100: cue 24/25
  { say: at(24, "[আরবি"), mean: at(25, "অর্থ") },
];

const beats = sentenceBeats.map((b) => ({
  say: f(b.say) - 2,
  mean: f(b.mean) - 4,
}));

const out = `// AUTO-GENERATED by scripts/gen-timing.mjs from data/day10.srt — do not edit by hand.
export const FPS = ${FPS};
export const TOTAL_FRAMES = ${TOTAL_FRAMES};
export const SCENES = ${JSON.stringify(scenes, null, 2)} as const;
export type SceneId = (typeof SCENES)[number]["id"];
export const BEATS = ${JSON.stringify(beats, null, 2)};
`;

fs.writeFileSync(new URL("../src/timing.ts", import.meta.url), out);
console.log(`Generated src/timing.ts: ${TOTAL_FRAMES} frames (${(TOTAL_FRAMES / FPS).toFixed(2)}s), ${scenes.length} scenes.`);
for (const s of scenes) {
  console.log(`  ${s.id.padEnd(10)}: from frame ${String(s.from).padStart(4)} to ${String(s.from + s.dur).padStart(4)} (${(s.dur / 30).toFixed(2)}s)`);
}

