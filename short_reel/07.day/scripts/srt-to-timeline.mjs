// Reads public/reel7complete_ben.srt and writes src/data/timeline.generated.ts
// The SRT is the single source of truth for timing.
//
// Cue format used by the narration:  "<pronunciation>,"  then  "<meaning>।"
// Some cues contain BOTH (e.g. "মেয়ে। জাওজ," = meaning of word 4 + pronunciation of word 5).
// Such a cue is split in two: the first token gets the START of the cue, the second token
// gets the END of the cue (each lasting SPLIT_TOKEN_SEC).
import fs from "node:fs";
import path from "node:path";
import {fileURLToPath} from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const SRT = path.join(root, "public", "reel7complete_ben.srt");
const OUT = path.join(root, "src", "data", "timeline.generated.ts");
const SPLIT_TOKEN_SEC = 0.42;

const toSec = (t) => {
  const m = t.trim().match(/(\d+):(\d+):(\d+)[,.](\d+)/);
  return +m[1] * 3600 + +m[2] * 60 + +m[3] + +m[4] / 1000;
};

const raw = fs.readFileSync(SRT, "utf8").replace(/\r/g, "").trim();
const cues = raw.split(/\n\n+/).map((block) => {
  const lines = block.split("\n");
  const [a, b] = lines[1].split("-->");
  return {start: toSec(a), end: toSec(b), text: lines.slice(2).join(" ").trim()};
});

// tokenise cues -> {kind, text, start, end}
const tokens = [];
for (const cue of cues) {
  const parts = [...cue.text.matchAll(/([^,।]+)([,।])/g)].map((m) => ({
    text: m[1].trim(),
    kind: m[2] === "," ? "pron" : "meaning",
  }));
  if (parts.length === 1) {
    tokens.push({...parts[0], start: cue.start, end: cue.end});
  } else if (parts.length === 2) {
    tokens.push({...parts[0], start: cue.start, end: Math.min(cue.end, cue.start + SPLIT_TOKEN_SEC), split: true});
    tokens.push({...parts[1], start: Math.max(cue.start, cue.end - SPLIT_TOKEN_SEC), end: cue.end, split: true});
  } else {
    throw new Error(`Unexpected cue: ${cue.text}`);
  }
}

// pair pron -> meaning
const words = [];
for (let i = 0; i < tokens.length; i += 2) {
  const p = tokens[i];
  const m = tokens[i + 1];
  if (p.kind !== "pron" || !m || m.kind !== "meaning") {
    throw new Error(`Cue pairing broke at token ${i}: ${JSON.stringify(p)} / ${JSON.stringify(m)}`);
  }
  words.push({index: words.length, pron: p, meaning: m});
}

const r = (n) => Math.round(n * 1000) / 1000;
const body = words
  .map(
    (w) => `  {index: ${w.index}, pron: {text: ${JSON.stringify(w.pron.text)}, start: ${r(w.pron.start)}, end: ${r(w.pron.end)}}, meaning: {text: ${JSON.stringify(w.meaning.text)}, start: ${r(w.meaning.start)}, end: ${r(w.meaning.end)}}}`,
  )
  .join(",\n");

fs.writeFileSync(
  OUT,
  `// AUTO-GENERATED by scripts/srt-to-timeline.mjs from public/reel7complete_ben.srt — do not edit by hand.\n// Run \`npm run sync:srt\` after changing the SRT.\nexport type TimedText = {text: string; start: number; end: number};\nexport type TimelineWord = {index: number; pron: TimedText; meaning: TimedText};\nexport const TIMELINE: TimelineWord[] = [\n${body},\n];\n`,
);
console.log(`✔ ${words.length} words written to src/data/timeline.generated.ts`);
for (const w of words) {
  console.log(`${String(w.index + 1).padStart(2)}. ${w.pron.text} ${w.pron.start.toFixed(2)}–${w.pron.end.toFixed(2)}  |  ${w.meaning.text} ${w.meaning.start.toFixed(2)}–${w.meaning.end.toFixed(2)}`);
}
