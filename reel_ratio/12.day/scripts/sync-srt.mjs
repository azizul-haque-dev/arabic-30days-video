// Embeds subtitles.srt into src/generated/subtitles.ts so the Remotion bundle can read it synchronously.
// Run after replacing subtitles.srt:  npm run sync:srt
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const cfg = JSON.parse(readFileSync(join(root, "episode.config.json"), "utf8"));
const raw = readFileSync(join(root, cfg.srtFile), "utf8");
writeFileSync(
  join(root, "src/generated/subtitles.ts"),
  `// AUTO-GENERATED by scripts/sync-srt.mjs from ${cfg.srtFile}. Do not edit by hand.\nexport const SRT_RAW: string = ${JSON.stringify(raw)};\n`,
);
console.log(`synced ${cfg.srtFile} (${raw.length} chars)`);
