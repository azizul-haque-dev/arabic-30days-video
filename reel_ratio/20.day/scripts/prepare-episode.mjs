#!/usr/bin/env node
/**
 * Build-time episode preparation (reusable for every episode).
 *
 *  1. Audio discovery  — looks for public/audio/<audioBaseName>.mp3 (or .wav)
 *                        and writes src/generated/audio.ts
 *  2. SRT parsing      — parses content/<srtFile> and writes src/generated/srt.ts
 *
 * Remotion cannot scan the file system from the browser, so this runs BEFORE
 * `remotion studio` / `remotion render` (see the npm scripts in package.json).
 *
 * Flags:
 *   --strict          exit with an error when the audio file is missing
 *                     (used by `npm run build`). Without it a missing file only
 *                     prints a warning, so you can preview without audio.
 *   ALLOW_NO_AUDIO=1  env var that disables --strict (render a silent video).
 */
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const strict = process.argv.includes("--strict") && process.env.ALLOW_NO_AUDIO !== "1";

// ---- Episode settings (change these for the next episode) -----------------
const EPISODE = {
  audioBaseName: "day-20", // public/audio/day-20.mp3 | .wav
  srtFile: "day20.srt", // content/day20.srt
};
// ---------------------------------------------------------------------------

const AUDIO_EXTENSIONS = [".wav", ".mp3"];
const publicDir = path.join(root, "public");
const audioDir = path.join(publicDir, "audio");
const generatedDir = path.join(root, "src", "generated");
fs.mkdirSync(generatedDir, { recursive: true });

// Search order: public/audio.wav, public/audio.mp3, then public/audio/audio.*, public/audio/<audioBaseName>.*
const candidates = [];
for (const ext of AUDIO_EXTENSIONS) candidates.push(`audio${ext}`);
for (const ext of AUDIO_EXTENSIONS) candidates.push(`audio/audio${ext}`);
for (const ext of AUDIO_EXTENSIONS) candidates.push(`audio/${EPISODE.audioBaseName}${ext}`);

// ---- 1. Audio discovery -----------------------------------------------------
const audioSrc = candidates.find((c) => fs.existsSync(path.join(publicDir, c))) ?? null; // relative to /public (for staticFile)
const expected = "public/audio.wav  (or public/audio.mp3)";

if (audioSrc) {
  console.log(`✔ Audio detected: public/${audioSrc}`);
} else {
  const msg =
    `\n✖ AUDIO FILE NOT FOUND\n` +
    `  Expected: ${expected}\n` +
    `  Save the narration there and run the command again.\n`;
  if (strict) {
    console.error(msg + "  (Set ALLOW_NO_AUDIO=1 to render without audio.)\n");
    process.exit(1);
  }
  console.warn(msg + "  Continuing WITHOUT audio (preview mode).\n");
}

fs.writeFileSync(
  path.join(generatedDir, "audio.ts"),
  `// AUTO-GENERATED by scripts/prepare-episode.mjs — do not edit.\n` +
    `export const AUDIO_SRC: string | null = ${JSON.stringify(audioSrc)};\n` +
    `export const AUDIO_EXPECTED_PATH = ${JSON.stringify(expected)};\n`,
);

// ---- 2. SRT parsing ---------------------------------------------------------
const srtPath = path.join(root, "content", EPISODE.srtFile);
if (!fs.existsSync(srtPath)) {
  console.error(`✖ SRT not found: content/${EPISODE.srtFile}`);
  process.exit(1);
}
const raw = fs.readFileSync(srtPath, "utf8").replace(/^\uFEFF/, "").replace(/\r\n/g, "\n");
const toSec = (t) => {
  const m = t.trim().match(/^(\d+):(\d+):(\d+)[,.](\d+)$/);
  if (!m) throw new Error(`Bad SRT timestamp: ${t}`);
  return Number(m[1]) * 3600 + Number(m[2]) * 60 + Number(m[3]) + Number(m[4].padEnd(3, "0")) / 1000;
};
const entries = raw
  .split(/\n\s*\n/)
  .map((b) => b.trim())
  .filter(Boolean)
  .map((block) => {
    const lines = block.split("\n");
    const index = Number(lines[0]);
    const [a, b] = lines[1].split("-->");
    return { index, start: toSec(a), end: toSec(b), text: lines.slice(2).join(" ").trim() };
  });

entries.forEach((e, i) => {
  if (e.index !== i + 1) throw new Error(`SRT numbering gap at entry ${i + 1}`);
  if (e.end <= e.start) throw new Error(`SRT entry ${e.index}: end <= start`);
});
console.log(`✔ SRT parsed: ${entries.length} entries, ends at ${entries.at(-1).end}s`);

fs.writeFileSync(
  path.join(generatedDir, "srt.ts"),
  `// AUTO-GENERATED by scripts/prepare-episode.mjs from content/${EPISODE.srtFile} — do not edit.\n` +
    `export type SrtEntry = { index: number; start: number; end: number; text: string };\n` +
    `export const SRT: SrtEntry[] = ${JSON.stringify(entries, null, 2)};\n`,
);
